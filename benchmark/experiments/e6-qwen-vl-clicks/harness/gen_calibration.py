#!/usr/bin/env python3
"""Emit the calibration pages.

Two variants, because they answer different questions:

    page/calibration.html        crosses *with* their coordinates printed beside
                                 them — for a human checking the instrument
    page/calibration-plain.html  crosses only, no numbers anywhere — the one the
                                 model is measured against

The plain page is the measurement frame. Printing the coordinates next to the
crosses would let a model answer by reading text, which measures OCR instead of
the coordinate space the experiment is asking about.

    python3 harness/gen_calibration.py            # write both pages
    python3 harness/gen_calibration.py --check    # verify both are up to date
"""

from __future__ import annotations

import os
import sys

XS = (128, 384, 640, 896, 1152)
YS = (60, 180, 300, 420, 540)
HERE = os.path.dirname(os.path.abspath(__file__))
LABELLED = os.path.join(HERE, "page", "calibration.html")
PLAIN = os.path.join(HERE, "page", "calibration-plain.html")

STYLE = """<style>
  html, body { margin: 0; padding: 0; width: 1280px; height: 600px;
               background: #0b0d10; overflow: hidden; }
  body { font: 10px/1 ui-monospace, monospace; color: #d7dbe0; }
  .cross { position: absolute; width: 15px; height: 15px; }
  .cross .v { position: absolute; left: 7px; top: 0; width: 1px; height: 15px;
              background: #ff4d4d; }
  .cross .h { position: absolute; top: 7px; left: 0; height: 1px; width: 15px;
              background: #ff4d4d; }
  .cross .dot { position: absolute; left: 6px; top: 6px; width: 3px; height: 3px;
                background: #ffffff; }
  .name { position: absolute; white-space: nowrap; color: #9aa4b2; }
  .corner { position: absolute; width: 9px; height: 9px; border: 1px solid #3b82f6; }
  .title { position: absolute; left: 8px; top: 8px; color: #6b7280; }
</style>
"""

CORNERS = """  <div class="corner" style="left:0;top:0"></div>
  <div class="corner" style="left:1271px;top:0"></div>
  <div class="corner" style="left:0;top:591px"></div>
  <div class="corner" style="left:1271px;top:591px"></div>
"""


def _crosses(with_labels: bool) -> str:
    parts = []
    for y in YS:
        for x in XS:
            parts.append(
                f'  <div class="cross" data-x="{x}" data-y="{y}" '
                f'style="left:{x - 7}px;top:{y - 7}px">'
                f'<div class="v"></div><div class="h"></div><div class="dot"></div></div>\n'
            )
            if with_labels:
                parts.append(
                    f'  <div class="name" style="left:{x + 11}px;top:{y - 15}px">{x},{y}</div>\n'
                )
    return "".join(parts)


def labelled_page() -> str:
    return (
        "<!doctype html>\n<meta charset=\"utf-8\">\n<title>E6 calibration (labelled)</title>\n"
        "<!-- Generated by harness/gen_calibration.py. Do not hand-edit.\n\n"
        "     25 crosses at x = 128, 384, 640, 896, 1152 and y = 60, 180, 300, 420, 540,\n"
        "     each printed with its own coordinate. For a human checking the instrument;\n"
        "     the model is measured against calibration-plain.html instead. -->\n"
        + STYLE
        + "<body>\n"
        '  <div class="title">E6 - 25 crosses, viewport 1280x600, coordinate printed beside each cross</div>\n'
        + CORNERS
        + _crosses(with_labels=True)
        + "</body>\n"
    )


def plain_page() -> str:
    return (
        "<!doctype html>\n<meta charset=\"utf-8\">\n<title>E6 calibration</title>\n"
        "<!-- Generated by harness/gen_calibration.py. Do not hand-edit.\n\n"
        "     25 crosses at x = 128, 384, 640, 896, 1152 and y = 60, 180, 300, 420, 540.\n"
        "     No coordinates appear anywhere on this page: a model answering here has to\n"
        "     localise the cross visually, which is the thing being measured. -->\n"
        + STYLE
        + "<body>\n"
        + CORNERS
        + _crosses(with_labels=False)
        + "</body>\n"
    )


def main() -> int:
    wanted = {LABELLED: labelled_page(), PLAIN: plain_page()}
    if "--check" in sys.argv:
        stale = []
        for path, expected in wanted.items():
            try:
                with open(path, encoding="utf-8") as fh:
                    current = fh.read()
            except FileNotFoundError:
                stale.append(f"{path} is missing")
                continue
            if current != expected:
                stale.append(f"{path} is stale")
        if stale:
            print("; ".join(stale) + " — re-run harness/gen_calibration.py", file=sys.stderr)
            return 1
        print(f"both calibration pages are up to date ({len(YS) * len(XS)} crosses each)")
        return 0

    for path, content in wanted.items():
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(content)
        print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
